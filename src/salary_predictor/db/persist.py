# src/salary_predictor/db/persist.py
#
# Saves predictions and analysis results to Supabase.
#
# We save in two steps:
#   1. Save all predictions (one row per prediction)
#   2. Save the analysis (narrative + chart + stats)
#
# Both are linked by a run_id — a unique ID generated once
# per pipeline run so we can group them on the dashboard.

import logging
import uuid
from datetime import datetime, timezone

from salary_predictor.db.supabase_client import get_client

logger = logging.getLogger(__name__)

# How many predictions to insert at once.
# Supabase has a request size limit so we insert in batches.
BATCH_SIZE = 100


def save_predictions(predictions: list, run_id: str) -> int:
    """
    Save all predictions to the predictions table.

    We insert in batches of 100 to avoid hitting Supabase
    request size limits.

    Args:
        predictions: list of prediction dicts from run_pipeline()
        run_id:      unique ID linking this batch to its analysis

    Returns:
        number of rows successfully inserted
    """
    client = get_client()
    total_saved = 0

    # Split predictions into batches
    batches = [
        predictions[i : i + BATCH_SIZE]
        for i in range(0, len(predictions), BATCH_SIZE)
    ]

    logger.info(
        "Saving %d predictions in %d batches...",
        len(predictions), len(batches),
    )

    for batch_number, batch in enumerate(batches, start=1):
        # Build the rows to insert
        rows = []
        for item in batch:
            rows.append({
                "run_id":               run_id,
                "experience_level":     item["experience_level"],
                "employment_type":      item["employment_type"],
                "company_size":         item["company_size"],
                "remote_ratio":         item["remote_ratio"],
                "work_year":            item["work_year"],
                "job_title":            item["job_title"],
                "employee_residence":   item["employee_residence"],
                "company_location":     item["company_location"],
                "predicted_salary_usd": item["predicted_salary_usd"],
            })

        try:
            client.table("predictions").insert(rows).execute()
            total_saved += len(rows)
            logger.info(
                "Batch %d / %d saved (%d rows)",
                batch_number, len(batches), len(rows),
            )

        except Exception as error:
            logger.error("Batch %d failed: %s", batch_number, error)

    logger.info("Predictions saved: %d / %d", total_saved, len(predictions))
    return total_saved


def save_analysis(
    run_id:      str,
    narrative:   str,
    chart_base64: str,
    stats:       dict,
) -> bool:
    """
    Save the LLM narrative, chart, and stats to the analyses table.

    Args:
        run_id:       unique ID linking this analysis to its predictions
        narrative:    the text generated by Ollama
        chart_base64: the PNG chart encoded as a base64 string
        stats:        aggregated salary stats dict

    Returns:
        True if saved successfully, False if it failed
    """
    client = get_client()

    row = {
        "run_id":       run_id,
        "run_label":    f"Run {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M')}",
        "narrative":    narrative,
        "chart_base64": chart_base64,
        "stats":        stats,
    }

    try:
        client.table("analyses").insert(row).execute()
        logger.info("Analysis saved to Supabase — run_id: %s", run_id)
        return True

    except Exception as error:
        logger.error("Failed to save analysis: %s", error)
        return False